package org.apache.gravitino.catalog.oracle.operation;

import com.google.common.collect.ImmutableMap;
import java.util.Collections;
import java.util.Locale;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

/** Unit test for the DDL generated by {@link OracleSchemaOperations}. */
public class TestOracleSchemaOperationsSqlGeneration {

  private final OracleSchemaOperations operations = new OracleSchemaOperations();

  /**
   * An Oracle schema is the namespace owned by a database user, so creating one creates a user.
   * {@code NO AUTHENTICATION} makes it a namespace only, with no way to log in.
   */
  @Test
  public void testCreateSchemaCreatesAnUnauthenticatedUser() {
    Assertions.assertEquals(
        "CREATE USER \"test_schema\" NO AUTHENTICATION",
        operations.generateCreateDatabaseSql("test_schema", null, Collections.emptyMap()));
    Assertions.assertEquals(
        "CREATE USER \"test_schema\" NO AUTHENTICATION",
        operations.generateCreateDatabaseSql("test_schema", "", Collections.emptyMap()));
  }

  /** An embedded quote is doubled so that it cannot terminate the quoting early. */
  @Test
  public void testCreateSchemaEscapesQuoteInSchemaName() {
    Assertions.assertEquals(
        "CREATE USER \"a\"\"b\" NO AUTHENTICATION",
        operations.generateCreateDatabaseSql("a\"b", null, Collections.emptyMap()));
  }

  /**
   * Oracle has no {@code COMMENT ON SCHEMA}, so a comment carrying anything but the Gravitino
   * entity id cannot be stored and is rejected rather than silently dropped.
   */
  @Test
  public void testCreateSchemaAcceptsOnlyTheEntityIdComment() {
    // Gravitino always passes a comment, holding the entity id, which is not persisted.
    Assertions.assertEquals(
        "CREATE USER \"test_schema\" NO AUTHENTICATION",
        operations.generateCreateDatabaseSql(
            "test_schema", "some comment", Collections.emptyMap()));
  }

  @Test
  public void testCreateSchemaRejectsProperties() {
    Assertions.assertThrows(
        UnsupportedOperationException.class,
        () ->
            operations.generateCreateDatabaseSql(
                "test_schema", null, ImmutableMap.of("key", "value")));
  }

  /**
   * The tablespace quota is a separate statement, because Oracle accepts only one statement per
   * call and the tablespace has to be read from the database first. Without it a {@code NO
   * AUTHENTICATION} user has no quota and every {@code CREATE TABLE} in the schema fails with
   * ORA-01950, since Oracle checks the quota of the schema owner rather than of the caller.
   */
  @Test
  public void testGrantUnlimitedQuota() {
    Assertions.assertEquals(
        "ALTER USER \"test_schema\" QUOTA UNLIMITED ON \"USERS\"",
        OracleSchemaOperations.grantUnlimitedQuotaSql("test_schema", "USERS"));
    Assertions.assertEquals(
        "ALTER USER \"a\"\"b\" QUOTA UNLIMITED ON \"SYSTEM\"",
        OracleSchemaOperations.grantUnlimitedQuotaSql("a\"b", "SYSTEM"));
  }

  @Test
  public void testDropSchemaWithoutCascade() {
    Assertions.assertEquals(
        "DROP USER \"test_schema\"", operations.generateDropDatabaseSql("test_schema", false));
  }

  /**
   * Oracle drops a schema by dropping the user that owns it. {@code CASCADE} takes the contained
   * objects with it, which a plain drop refuses to do.
   */
  @Test
  public void testDropSchemaWithCascade() {
    Assertions.assertEquals(
        "DROP USER \"test_schema\" CASCADE",
        operations.generateDropDatabaseSql("test_schema", true));
  }

  @Test
  public void testDropSchemaEscapesQuoteInSchemaName() {
    Assertions.assertEquals(
        "DROP USER \"a\"\"b\" CASCADE", operations.generateDropDatabaseSql("a\"b", true));
  }

  @Test
  public void testReservedSchemaNames() {
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("sys"));
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("system"));
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("xdb"));
    // Oracle stores an unquoted name folded to upper case, so the match is case insensitive.
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("SYS"));
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("Xdb"));
  }

  /**
   * APEX installs one schema per release, named {@code APEX_} followed by six digits, so the set of
   * reserved names cannot be enumerated ahead of time and has to be matched on shape.
   */
  @Test
  public void testVersionedApexSchemasAreReserved() {
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("APEX_040200"));
    Assertions.assertTrue(OracleSchemaOperations.isReservedSchema("apex_050100"));
  }

  @Test
  public void testApexLookAlikesAreNotReserved() {
    // Five digits is not a release schema.
    Assertions.assertFalse(OracleSchemaOperations.isReservedSchema("APEX_04020"));
    Assertions.assertFalse(OracleSchemaOperations.isReservedSchema("apex_reports"));
    Assertions.assertFalse(OracleSchemaOperations.isReservedSchema("sales"));
  }

  @Test
  public void testSystemSchemasAreAllLowerCase() {
    // The set is looked up against a lower cased name, so an entry in any other case never matches.
    for (String schema : OracleSchemaOperations.SYSTEM_SCHEMAS) {
      Assertions.assertEquals(schema.toLowerCase(Locale.ROOT), schema, schema);
      Assertions.assertTrue(OracleSchemaOperations.isReservedSchema(schema), schema);
    }
  }
}
