  /**
   * Oracle stores comments through {@code COMMENT ON}, a separate statement, so the CREATE TABLE
   * must not carry one; it would be a syntax error.
   */
  @Test
  public void testCreateTableDoesNotInlineComments() {
    JdbcColumn col =
        JdbcColumn.builder()
            .withName("col1")
            .withType(Types.IntegerType.get())
            .withComment("column comment")
            .build();

    String sql = createTableSql(new JdbcColumn[] {col}, "table comment", Indexes.EMPTY_INDEXES);

    Assertions.assertFalse(sql.contains("table comment"), sql);
    Assertions.assertFalse(sql.contains("column comment"), sql);
    Assertions.assertFalse(sql.contains("COMMENT"), sql);
  }

  @Test
  public void testCommentStatements() {
    JdbcColumn commented =
        JdbcColumn.builder()
            .withName("col1")
            .withType(Types.IntegerType.get())
            .withComment("column comment")
            .build();

    List<String> statements =
        ops.generateCommentSqls(
            TABLE,
            new JdbcColumn[] {commented, column("col2", Types.IntegerType.get())},
            "table comment");

    // The table comment has to run first, since it carries the Gravitino entity id.
    Assertions.assertEquals(
        List.of(
            "COMMENT ON TABLE " + QUOTED + " IS 'table comment'",
            "COMMENT ON COLUMN " + QUOTED + ".\"col1\" IS 'column comment'"),
        statements);
  }

  @Test
  public void testCommentStatementsAreEmptyWithoutComments() {
    Assertions.assertTrue(
        ops.generateCommentSqls(
                TABLE, new JdbcColumn[] {column("col1", Types.IntegerType.get())}, null)
            .isEmpty());
  }

  /** A single quote is escaped by doubling it, which keeps injected text inside the literal. */
  @Test
  public void testCommentStatementsEscapeQuote() {
    List<String> statements =
        ops.generateCommentSqls(
            TABLE,
            new JdbcColumn[] {column("col1", Types.IntegerType.get())},
            "owner's comment; DROP TABLE marker; --");

    Assertions.assertEquals(
        List.of("COMMENT ON TABLE " + QUOTED + " IS 'owner''s comment; DROP TABLE marker; --'"),
        statements);
  }

  /** A backslash is an ordinary character in an Oracle string literal and must survive verbatim. */
  @Test
  public void testCommentStatementsKeepBackslashVerbatim() {
    List<String> statements =
        ops.generateCommentSqls(
            TABLE, new JdbcColumn[] {column("col1", Types.IntegerType.get())}, "C:\\data\\notes");

    Assertions.assertEquals(
        List.of("COMMENT ON TABLE " + QUOTED + " IS 'C:\\data\\notes'"), statements);
    Assertions.assertFalse(statements.get(0).contains("\\\\"), statements.get(0));
  }

