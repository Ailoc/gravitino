  @Test
  public void testAlterTableAddColumn() {
    String sql =
        singleAlterSql(TableChange.addColumn(new String[] {"col2"}, Types.IntegerType.get()));

    Assertions.assertTrue(
        sql.startsWith("ALTER TABLE " + QUOTED + " ADD (\"col2\" number(10)"), sql);
    Assertions.assertTrue(sql.endsWith(")"), sql);
    // Oracle leaves a new column nullable unless NOT NULL is stated.
    Assertions.assertFalse(sql.contains("NOT NULL"), sql);
    Assertions.assertFalse(sql.contains("DEFAULT"), sql);
  }

