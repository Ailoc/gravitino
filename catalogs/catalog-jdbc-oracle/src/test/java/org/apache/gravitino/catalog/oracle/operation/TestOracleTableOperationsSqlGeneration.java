  /**
   * The Oracle driver accepts exactly one statement per call, so every generated statement has to
   * stand alone and none may carry the terminator SQL*Plus expects.
   */
  @Test
  public void testNoGeneratedStatementCarriesASemicolon() {
    ops.withLazyLoadTable(
        tableOf(column("col1", Types.IntegerType.get()), column("col2", Types.IntegerType.get())));

    List<String> statements =
        alterSql(
            TableChange.renameColumn(new String[] {"col1"}, "col3"),
            TableChange.updateColumnType(new String[] {"col2"}, Types.LongType.get()),
            TableChange.updateComment("new comment"));

    Assertions.assertEquals(3, statements.size(), statements.toString());
    for (String statement : statements) {
      Assertions.assertFalse(statement.contains(";"), statement);
      Assertions.assertFalse(statement.contains("\n"), statement);
    }
  }

  @Test
  public void testAlterTableKeepsChangesInOrder() {
    ops.withLazyLoadTable(tableOf(column("col1", Types.IntegerType.get())));

    List<String> statements =
        alterSql(
            TableChange.renameColumn(new String[] {"col1"}, "col3"),
            TableChange.deleteColumn(new String[] {"col1"}, false));

    Assertions.assertEquals(
        List.of(
            "ALTER TABLE " + QUOTED + " RENAME COLUMN \"col1\" TO \"col3\"",
            "ALTER TABLE " + QUOTED + " DROP COLUMN \"col1\""),
        statements);
  }

  @Test
  public void testDatetimePrecision() {
    // The Oracle driver reports the fractional seconds as the column scale and folds the precision
    // into the type name, so the column size arithmetic the base class documents does not apply.
    Assertions.assertEquals(6, ops.calculateDatetimePrecision("TIMESTAMP(6)", 11, 6));
    Assertions.assertEquals(
        3, ops.calculateDatetimePrecision("TIMESTAMP(3) WITH TIME ZONE", 13, 3));
    // DATE carries a time of day to the second and reads back as a timestamp of precision zero.
    Assertions.assertEquals(0, ops.calculateDatetimePrecision("date", 7, 0));
    // Non temporal types report no precision.
    Assertions.assertNull(ops.calculateDatetimePrecision("number", 10, 2));
    Assertions.assertNull(ops.calculateDatetimePrecision("varchar2", 100, 0));
  }

  @Test
  public void testQuoteIdentifierUsesDoubleQuotes() {
    Assertions.assertEquals("\"col1\"", ops.quoteIdentifier("col1"));
  }

  /**
   * Strips the surrounding {@code IS '...'} so the comment can be read back as Gravitino stores it.
   */
  private static String unwrapComment(String sql) {
    int start = sql.indexOf("IS '") + 4;
    return sql.substring(start, sql.length() - 1).replace("''", "'");
  }
