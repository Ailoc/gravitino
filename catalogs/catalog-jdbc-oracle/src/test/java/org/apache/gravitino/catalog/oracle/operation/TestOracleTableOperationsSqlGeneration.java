  /** The Gravitino entity id held in the existing comment has to be carried over to the new one. */
  @Test
  public void testAlterTableUpdateTableCommentKeepsEntityId() {
    StringIdentifier identifier = StringIdentifier.fromId(42L);
    String existingComment = StringIdentifier.addToComment(identifier, "old comment");
    ops.withLazyLoadTable(JdbcTable.builder().withName(TABLE).withComment(existingComment).build());

    String sql = singleAlterSql(TableChange.updateComment("new comment"));

    Assertions.assertTrue(sql.startsWith("COMMENT ON TABLE " + QUOTED + " IS '"), sql);
    Assertions.assertTrue(sql.contains("new comment"), sql);
    StringIdentifier carried = StringIdentifier.fromComment(unwrapComment(sql));
    Assertions.assertNotNull(carried, sql);
    Assertions.assertEquals(identifier.id(), carried.id(), sql);
  }

