/**
 * Table operations for Oracle.
 *
 * <p>Oracle supports {@code ALTER SESSION SET CURRENT_SCHEMA}, which the driver exposes through
 * {@link Connection#setSchema}. The schema is therefore selected once per connection and every
 * generated statement refers to the table by its unqualified name, as the PostgreSQL catalog does.
 * Oracle has no catalog level, so {@link Connection#setCatalog} must not be called.
 *
 * <p>The Oracle driver accepts exactly one statement per {@link java.sql.Statement} call and
 * rejects the trailing semicolon that terminates a statement in SQL*Plus. Every generated statement
 * here is therefore a single semicolon-free statement, and {@link #create} and {@link #alterTable}
 * are overridden to run the statements of an operation one at a time instead of handing the driver
 * a batch.
 */
public class OracleTableOperations extends JdbcTableOperations implements RequireDatabaseOperation {

  /** Delimiter Oracle uses for a quoted identifier, doubled where it appears inside one. */
  public static final String ORACLE_QUOTE = "\"";

  private static final String NEW_LINE = "\n";
  private static final String ALTER_TABLE = "ALTER TABLE ";
  private static final String TABLE_COMMENT = "COMMENT ON TABLE ";
  private static final String COLUMN_COMMENT = "COMMENT ON COLUMN ";
  private static final String IS = " IS '";
  private static final String IDENTITY_CLAUSE = "GENERATED BY DEFAULT AS IDENTITY";
  private static final String NOT_SUPPORT_NESTED_COLUMN_MSG =
      "Oracle does not support nested column names.";

  private OracleSchemaOperations schemaOperations;

  /**
   * Wraps an identifier in Oracle quoting, doubling any embedded quote character.
   *
   * @param identifier the identifier to quote
   * @return the quoted identifier
   */
  public static String quote(String identifier) {
    return ORACLE_QUOTE
        + identifier.replace(ORACLE_QUOTE, ORACLE_QUOTE + ORACLE_QUOTE)
        + ORACLE_QUOTE;
  }

  /**
   * Escapes a value for use inside a single-quoted Oracle string literal.
   *
   * <p>Only the quote itself needs doubling. Oracle does not treat the backslash as an escape
   * character in string literals, so {@link JdbcConnectorUtils#escapeSqlLiteral} must not be used
   * here as it would corrupt values containing backslashes.
   *
   * @param value the literal value to escape
   * @return the escaped literal value, without surrounding quotes
   */
  public static String escapeLiteral(String value) {
    return String.valueOf(value).replace("'", "''");
  }

  @Override
  public void setDatabaseOperation(DatabaseOperation databaseOperation) {
    this.schemaOperations = (OracleSchemaOperations) databaseOperation;
  }

  /**
   * Creates the table and then attaches the comments, one statement at a time.
   *
   * <p>The base implementation hands a single string to the driver, which works for MySQL and
   * PostgreSQL because both accept a multi-statement script. Oracle does not, so the statements are
   * generated separately and executed in order. Oracle commits implicitly around every DDL
   * statement, so a failure part way through leaves the earlier statements applied; this is the
   * same exposure the PostgreSQL catalog has.
   */
  @Override
  public void create(
      String schemaName,
      String tableName,
      JdbcColumn[] columns,
      String comment,
      Map<String, String> properties,
      Transform[] partitioning,
      Distribution distribution,
      Index[] indexes,
      SortOrder[] sortOrders)
      throws TableAlreadyExistsException {
    if (ArrayUtils.isNotEmpty(sortOrders)) {
      throw new UnsupportedOperationException("Oracle does not support sort orders.");
    }
    LOG.info("Attempting to create table {} in schema {}", tableName, schemaName);
    try (Connection connection = getConnection(schemaName)) {
      List<String> statements = new ArrayList<>();
      statements.add(
          generateCreateTableSql(
              tableName, columns, comment, properties, partitioning, distribution, indexes));
      statements.addAll(generateCommentSqls(tableName, columns, comment));
      for (String sql : statements) {
        JdbcConnectorUtils.executeUpdate(connection, sql);
      }
      LOG.info("Created table {} in schema {} with SQL:\n{}", tableName, schemaName, statements);
    } catch (SQLException se) {
      throw exceptionMapper.toGravitinoException(se);
    }
  }

  @Override
  public List<String> listTables(String schemaName) throws NoSuchSchemaException {
    try (Connection connection = getConnection(schemaName)) {
      if (!schemaOperations.schemaExists(connection, schemaName)) {
        throw new NoSuchSchemaException("No such schema: %s", schemaName);
      }
      List<String> names = Lists.newArrayList();
      try (ResultSet tables = getTables(connection)) {
        while (tables.next()) {
          if (Objects.equals(tables.getString("TABLE_SCHEM"), schemaName)) {
            names.add(tables.getString("TABLE_NAME"));
          }
        }
      }
      LOG.info("Finished listing tables size {} for schema name {} ", names.size(), schemaName);
      return names;
    } catch (SQLException se) {
      throw exceptionMapper.toGravitinoException(se);
    }
  }

  @Override
  protected JdbcTable.Builder getTableBuilder(
      ResultSet tablesResult, String schemaName, String tableName) throws SQLException {
    boolean found = false;
    JdbcTable.Builder builder = null;
    while (tablesResult.next() && !found) {
      if (Objects.equals(tablesResult.getString("TABLE_NAME"), tableName)
          && Objects.equals(tablesResult.getString("TABLE_SCHEM"), schemaName)) {
        builder = getBasicJdbcTableInfo(tablesResult).withDatabaseName(schemaName);
        found = true;
      }
    }

    if (!found) {
      throw new NoSuchTableException("Table %s does not exist in %s.", tableName, schemaName);
    }
    return builder;
  }

  @Override
  protected JdbcColumn.Builder getColumnBuilder(
      ResultSet columnsResult, String schemaName, String tableName) throws SQLException {
    if (Objects.equals(columnsResult.getString("TABLE_NAME"), tableName)
        && Objects.equals(columnsResult.getString("TABLE_SCHEM"), schemaName)) {
      return getBasicJdbcColumnInfo(columnsResult);
    }
    return null;
  }

  /**
   * Generates the {@code CREATE TABLE} statement alone.
   *
   * <p>The {@code comment} argument is deliberately unused: Oracle stores comments through {@code
   * COMMENT ON}, a separate statement, so they are generated by {@link #generateCommentSqls} and
   * run after this one.
   *
   * @param tableName the table name
   * @param columns the columns of the table
   * @param comment the table comment, emitted separately
   * @param properties the table properties, which Oracle does not persist
   * @param partitioning the partitioning transforms, unsupported here
   * @param distribution the distribution, unsupported by Oracle
   * @param indexes the primary key and unique constraints to declare inline
   * @return the statement creating the table
   */
  @Override
  protected String generateCreateTableSql(
      String tableName,
      JdbcColumn[] columns,
      String comment,
      Map<String, String> properties,
      Transform[] partitioning,
      Distribution distribution,
      Index[] indexes) {
    if (ArrayUtils.isNotEmpty(partitioning)) {
      throw new UnsupportedOperationException("Currently we do not support Partitioning in Oracle");
    }
    Preconditions.checkArgument(
        Distributions.NONE.equals(distribution), "Oracle does not support distribution");
    if (MapUtils.isNotEmpty(properties)) {
      // Oracle has no table level key-value properties, only per attribute settings such as
      // compression, which Gravitino does not model.
      throw new IllegalArgumentException("Properties are not supported yet");
    }

    StringBuilder sqlBuilder = new StringBuilder();
    sqlBuilder.append("CREATE TABLE ").append(quote(tableName)).append(" (").append(NEW_LINE);

    for (int i = 0; i < columns.length; i++) {
      JdbcColumn column = columns[i];
      sqlBuilder.append("    ").append(quote(column.name()));
      appendColumnDefinition(column, sqlBuilder);
      if (i < columns.length - 1) {
        sqlBuilder.append(",").append(NEW_LINE);
      }
    }
    appendIndexesSql(indexes, sqlBuilder);
    sqlBuilder.append(NEW_LINE).append(")");

    String result = sqlBuilder.toString();
    LOG.info("Generated create table:{} sql: {}", tableName, result);
    return result;
  }

  /**
   * Generates the {@code COMMENT ON} statements carrying the table comment and the column comments.
   *
   * @param tableName the table name
   * @param columns the columns of the table
   * @param comment the table comment, which also carries the Gravitino entity id
   * @return one statement per comment, in the order they should run
   */
  @VisibleForTesting
  List<String> generateCommentSqls(String tableName, JdbcColumn[] columns, String comment) {
    List<String> result = new ArrayList<>();
    if (StringUtils.isNotEmpty(comment)) {
      result.add(tableCommentSql(tableName, comment));
    }
    for (JdbcColumn column : columns) {
      if (StringUtils.isNotEmpty(column.comment())) {
        result.add(columnCommentSql(tableName, column.name(), column.comment()));
      }
    }
    return result;
  }

  @Override
  protected String generateRenameTableSql(String oldTableName, String newTableName) {
    return ALTER_TABLE + quote(oldTableName) + " RENAME TO " + quote(newTableName);
  }

  @Override
  protected String generateDropTableSql(String tableName) {
    return "DROP TABLE " + quote(tableName);
  }

  /**
   * Oracle moves a dropped table into the recycle bin, where it keeps occupying space and keeps its
   * name reserved. Purging skips the recycle bin, which is the only thing that distinguishes it
   * from a plain drop here.
   */
  @Override
  protected String generatePurgeTableSql(String tableName) {
    return "DROP TABLE " + quote(tableName) + " PURGE";
  }

  /**
   * Runs the statements of an alter operation one at a time, for the same reason {@link #create} is
   * overridden.
   *
   * @param schemaName the schema the table belongs to
   * @param tableName the table name
   * @param changes the changes to apply
   * @throws NoSuchTableException if the table does not exist
   */
  @Override
  public void alterTable(String schemaName, String tableName, TableChange... changes)
      throws NoSuchTableException {
    LOG.info("Attempting to alter table {} from schema {}", tableName, schemaName);
    try (Connection connection = getConnection(schemaName)) {
      List<String> statements = generateAlterTableSqls(schemaName, tableName, changes);
      if (statements.isEmpty()) {
        LOG.info("No changes to alter table {} from schema {}", tableName, schemaName);
        return;
      }
      for (String sql : statements) {
        JdbcConnectorUtils.executeUpdate(connection, sql);
      }
      LOG.info("Alter table {} from schema {}", tableName, schemaName);
    } catch (SQLException se) {
      throw exceptionMapper.toGravitinoException(se);
    }
  }

  /**
   * Returns the alter statements joined for logging.
   *
   * <p>The joined form is not executable, because the Oracle driver rejects a multi-statement
   * script. {@link #alterTable} runs {@link #generateAlterTableSqls} instead, and this override
   * exists to keep the abstract contract of the base class.
   *
   * @param schemaName the schema the table belongs to
   * @param tableName the table name
   * @param changes the changes to apply
   * @return the generated statements, joined by a newline
   */
  @Override
  protected String generateAlterTableSql(
      String schemaName, String tableName, TableChange... changes) {
    return String.join(NEW_LINE, generateAlterTableSqls(schemaName, tableName, changes));
  }

  /**
   * Generates one statement per table change.
   *
   * <p>Fewer changes need the current table loaded than in the PostgreSQL and SQL Server catalogs,
   * because Oracle's {@code MODIFY} clause restates a single attribute rather than replacing the
   * whole column definition. The table is loaded only where its existing state genuinely matters.
   *
   * @param schemaName the schema the table belongs to
   * @param tableName the table name
   * @param changes the changes to apply
   * @return the statements to run, empty if there is nothing to do
   */
  @VisibleForTesting
  List<String> generateAlterTableSqls(String schemaName, String tableName, TableChange... changes) {
    JdbcTable lazyLoadTable = null;
    List<String> alterSql = new ArrayList<>();
    for (TableChange change : changes) {
      if (change instanceof TableChange.UpdateComment) {
        // The existing comment is needed to carry the Gravitino entity id over to the new one.
        lazyLoadTable = getOrCreateTable(schemaName, tableName, lazyLoadTable);
        alterSql.add(updateCommentDefinition(lazyLoadTable, (TableChange.UpdateComment) change));
      } else if (change instanceof TableChange.SetProperty
          || change instanceof TableChange.RemoveProperty) {
        throw new IllegalArgumentException("Oracle does not support table properties.");
      } else if (change instanceof TableChange.AddColumn) {
        alterSql.addAll(addColumnFieldDefinition(tableName, (TableChange.AddColumn) change));
      } else if (change instanceof TableChange.RenameColumn) {
        alterSql.add(renameColumnFieldDefinition(tableName, (TableChange.RenameColumn) change));
      } else if (change instanceof TableChange.UpdateColumnDefaultValue) {
        alterSql.add(
            updateColumnDefaultValueDefinition(
                tableName, (TableChange.UpdateColumnDefaultValue) change));
      } else if (change instanceof TableChange.UpdateColumnType) {
        alterSql.add(updateColumnTypeDefinition(tableName, (TableChange.UpdateColumnType) change));
      } else if (change instanceof TableChange.UpdateColumnComment) {
        alterSql.add(
            updateColumnCommentDefinition(tableName, (TableChange.UpdateColumnComment) change));
      } else if (change instanceof TableChange.UpdateColumnPosition) {
        throw new IllegalArgumentException("Oracle does not support column position.");
      } else if (change instanceof TableChange.DeleteColumn) {
        lazyLoadTable = getOrCreateTable(schemaName, tableName, lazyLoadTable);
        String deleteColumnSql =
            deleteColumnFieldDefinition(lazyLoadTable, (TableChange.DeleteColumn) change);
        if (StringUtils.isNotEmpty(deleteColumnSql)) {
          alterSql.add(deleteColumnSql);
        }
      } else if (change instanceof TableChange.UpdateColumnNullability) {
        lazyLoadTable = getOrCreateTable(schemaName, tableName, lazyLoadTable);
        TableChange.UpdateColumnNullability updateColumnNullability =
            (TableChange.UpdateColumnNullability) change;
        validateUpdateColumnNullable(updateColumnNullability, lazyLoadTable);
        alterSql.add(updateColumnNullabilityDefinition(tableName, updateColumnNullability));
      } else if (change instanceof TableChange.AddIndex) {
        alterSql.add(addIndexDefinition(tableName, (TableChange.AddIndex) change));
      } else if (change instanceof TableChange.DeleteIndex) {
        alterSql.add(deleteIndexDefinition(tableName, (TableChange.DeleteIndex) change));
      } else if (change instanceof TableChange.UpdateColumnAutoIncrement) {
        alterSql.add(
            updateColumnAutoIncrementDefinition(
                tableName, (TableChange.UpdateColumnAutoIncrement) change));
      } else {
        throw new IllegalArgumentException(
            "Unsupported table change type: " + change.getClass().getName());
      }
    }
    return alterSql;
  }

  @Override
  protected Connection getConnection(String schema) throws SQLException {
    Connection connection = dataSource.getConnection();
    // Oracle has no catalog level, so only the schema is set.
    connection.setSchema(schema);
    return connection;
  }

  @Override
  protected ResultSet getTable(Connection connection, String schema, String tableName)
      throws SQLException {
    DatabaseMetaData metaData = connection.getMetaData();
    return metaData.getTables(null, schema, tableName, null);
  }

  @Override
  protected ResultSet getColumns(Connection connection, String schema, String tableName)
      throws SQLException {
    DatabaseMetaData metaData = connection.getMetaData();
    return metaData.getColumns(null, schema, tableName, null);
  }

  @Override
  protected ResultSet getIndexInfo(String schema, String tableName, DatabaseMetaData metaData)
      throws SQLException {
    return metaData.getIndexInfo(null, schema, tableName, false, false);
  }

  @Override
  protected ResultSet getPrimaryKeys(String schema, String tableName, DatabaseMetaData metaData)
      throws SQLException {
    return metaData.getPrimaryKeys(null, schema, tableName);
  }

  /**
   * The Oracle driver reports the fractional seconds of a timestamp as the column scale, and folds
   * the precision into the type name, so the column size arithmetic the base class documents does
   * not apply. {@code DATE} is included because it carries a time of day to the second and is read
   * back as a timestamp of precision zero.
   */
  @Override
  public Integer calculateDatetimePrecision(String typeName, int columnSize, int scale) {
    String normalized = OracleTypeConverter.normalize(typeName);
    if (normalized.startsWith(JdbcTypeConverter.TIMESTAMP)
        || JdbcTypeConverter.DATE.equals(normalized)) {
      return Math.max(scale, 0);
    }
    return null;
  }

  @Override
  protected String quoteIdentifier(String identifier) {
    return quote(identifier);
  }

  @VisibleForTesting
  static void appendIndexesSql(Index[] indexes, StringBuilder sqlBuilder) {
    if (indexes == null) {
      return;
    }
    for (Index index : indexes) {
      String fieldStr = getIndexFieldStr(index.fieldNames());
      sqlBuilder.append(",").append(NEW_LINE);
      switch (index.type()) {
        case PRIMARY_KEY:
          if (StringUtils.isNotEmpty(index.name())) {
            sqlBuilder.append("CONSTRAINT ").append(quote(index.name())).append(SPACE);
          }
          sqlBuilder.append("PRIMARY KEY (").append(fieldStr).append(")");
          break;
        case UNIQUE_KEY:
          if (StringUtils.isNotEmpty(index.name())) {
            sqlBuilder.append("CONSTRAINT ").append(quote(index.name())).append(SPACE);
          }
          sqlBuilder.append("UNIQUE (").append(fieldStr).append(")");
          break;
        default:
          throw new IllegalArgumentException("Oracle doesn't support index : " + index.type());
      }
    }
  }

  protected static String getIndexFieldStr(String[][] fieldNames) {
    return Arrays.stream(fieldNames)
        .map(
            colNames -> {
              if (colNames.length > 1) {
                throw new IllegalArgumentException(
                    "Index does not support complex fields in Oracle");
              }
              return quote(colNames[0]);
            })
        .collect(Collectors.joining(", "));
  }

  @VisibleForTesting
  static String updateColumnAutoIncrementDefinition(
      String tableName, TableChange.UpdateColumnAutoIncrement change) {
    if (change.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    String action = change.isAutoIncrement() ? IDENTITY_CLAUSE : "DROP IDENTITY";
    return modifyColumnSql(tableName, quote(change.fieldName()[0]) + SPACE + action);
  }

  @VisibleForTesting
  static String addIndexDefinition(String tableName, TableChange.AddIndex addIndex) {
    StringBuilder sqlBuilder = new StringBuilder(ALTER_TABLE + quote(tableName) + " ADD ");
    if (StringUtils.isNotEmpty(addIndex.getName())) {
      sqlBuilder.append("CONSTRAINT ").append(quote(addIndex.getName())).append(SPACE);
    }
    switch (addIndex.getType()) {
      case PRIMARY_KEY:
        sqlBuilder.append("PRIMARY KEY ");
        break;
      case UNIQUE_KEY:
        sqlBuilder.append("UNIQUE ");
        break;
      default:
        throw new IllegalArgumentException("Unsupported index type: " + addIndex.getType());
    }
    sqlBuilder.append("(").append(getIndexFieldStr(addIndex.getFieldNames())).append(")");
    return sqlBuilder.toString();
  }

  @VisibleForTesting
  static String deleteIndexDefinition(String tableName, TableChange.DeleteIndex deleteIndex) {
    // Dropping the constraint also drops the index Oracle created to back it.
    return ALTER_TABLE + quote(tableName) + " DROP CONSTRAINT " + quote(deleteIndex.getName());
  }

  private void appendColumnDefinition(JdbcColumn column, StringBuilder sqlBuilder) {
    sqlBuilder.append(SPACE).append(typeConverter.fromGravitino(column.dataType())).append(SPACE);

    if (column.autoIncrement()) {
      if (!Types.allowAutoIncrement(column.dataType())) {
        throw new IllegalArgumentException(
            "Unsupported auto-increment, column: "
                + column.name()
                + ", type: "
                + column.dataType());
      }
      // Oracle rejects a DEFAULT on an identity column and makes it implicitly NOT NULL, so neither
      // of the clauses a plain column gets may follow here.
      sqlBuilder.append(IDENTITY_CLAUSE);
      return;
    }

    // Oracle requires the DEFAULT clause to precede the nullability constraint.
    appendDefaultValue(column, sqlBuilder);
    if (!column.nullable()) {
      sqlBuilder.append("NOT NULL");
    }
  }

  private String updateCommentDefinition(JdbcTable jdbcTable, TableChange.UpdateComment change) {
    String newComment = change.getNewComment();
    if (null == StringIdentifier.fromComment(newComment)) {
      // Detect and add Gravitino id.
      if (StringUtils.isNotEmpty(jdbcTable.comment())) {
        StringIdentifier identifier = StringIdentifier.fromComment(jdbcTable.comment());
        if (null != identifier) {
          newComment = StringIdentifier.addToComment(identifier, newComment);
        }
      }
    }
    return tableCommentSql(jdbcTable.name(), newComment);
  }

  private List<String> addColumnFieldDefinition(String tableName, TableChange.AddColumn addColumn) {
    if (addColumn.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    if (!(addColumn.getPosition() instanceof TableChange.Default)) {
      throw new IllegalArgumentException("Oracle does not support column position.");
    }

    String col = addColumn.fieldName()[0];
    StringBuilder columnDefinition =
        new StringBuilder()
            .append(quote(col))
            .append(SPACE)
            .append(typeConverter.fromGravitino(addColumn.getDataType()))
            .append(SPACE);

    if (addColumn.isAutoIncrement()) {
      if (!Types.allowAutoIncrement(addColumn.getDataType())) {
        throw new IllegalArgumentException(
            "Unsupported auto-increment, column: "
                + Arrays.toString(addColumn.getFieldName())
                + ", type: "
                + addColumn.getDataType());
      }
      columnDefinition.append(IDENTITY_CLAUSE);
    } else {
      if (!Column.DEFAULT_VALUE_NOT_SET.equals(addColumn.getDefaultValue())) {
        columnDefinition
            .append("DEFAULT ")
            .append(columnDefaultValueConverter.fromGravitino(addColumn.getDefaultValue()))
            .append(SPACE);
      }
      if (!addColumn.isNullable()) {
        columnDefinition.append("NOT NULL");
      }
    }

    List<String> result = new ArrayList<>();
    result.add(addColumnSql(tableName, columnDefinition.toString()));

    if (StringUtils.isNotEmpty(addColumn.getComment())) {
      result.add(columnCommentSql(tableName, col, addColumn.getComment()));
    }
    return result;
  }

  private String renameColumnFieldDefinition(
      String tableName, TableChange.RenameColumn renameColumn) {
    if (renameColumn.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    return ALTER_TABLE
        + quote(tableName)
        + " RENAME COLUMN "
        + quote(renameColumn.fieldName()[0])
        + " TO "
        + quote(renameColumn.getNewName());
  }

  private String deleteColumnFieldDefinition(
      JdbcTable table, TableChange.DeleteColumn deleteColumn) {
    if (deleteColumn.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    String col = deleteColumn.fieldName()[0];
    if (!columnExists(table, col)) {
      if (BooleanUtils.isTrue(deleteColumn.getIfExists())) {
        return "";
      }
      throw new IllegalArgumentException("Delete column does not exist: " + col);
    }
    return ALTER_TABLE + quote(table.name()) + " DROP COLUMN " + quote(col);
  }

  private String updateColumnDefaultValueDefinition(
      String tableName, TableChange.UpdateColumnDefaultValue change) {
    if (change.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    String defaultValue = columnDefaultValueConverter.fromGravitino(change.getNewDefaultValue());
    // Unsetting a default converts to null, which Oracle spells DEFAULT NULL.
    return modifyColumnSql(
        tableName,
        quote(change.fieldName()[0])
            + " DEFAULT "
            + (defaultValue == null ? "NULL" : defaultValue));
  }

  private String updateColumnTypeDefinition(String tableName, TableChange.UpdateColumnType change) {
    if (change.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    // Oracle's MODIFY changes a single attribute, so nullability and the default survive untouched
    // and do not have to be restated as they do under SQL Server's ALTER COLUMN.
    return modifyColumnSql(
        tableName,
        quote(change.fieldName()[0])
            + SPACE
            + typeConverter.fromGravitino(change.getNewDataType()));
  }

  private String updateColumnCommentDefinition(
      String tableName, TableChange.UpdateColumnComment change) {
    if (change.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    return columnCommentSql(tableName, change.fieldName()[0], change.getNewComment());
  }

  private String updateColumnNullabilityDefinition(
      String tableName, TableChange.UpdateColumnNullability change) {
    if (change.fieldName().length > 1) {
      throw new UnsupportedOperationException(NOT_SUPPORT_NESTED_COLUMN_MSG);
    }
    return modifyColumnSql(
        tableName,
        quote(change.fieldName()[0]) + SPACE + (change.nullable() ? "NULL" : "NOT NULL"));
  }

  private static String tableCommentSql(String tableName, String comment) {
    return TABLE_COMMENT + quote(tableName) + IS + escapeLiteral(comment) + "'";
  }

  private static String columnCommentSql(String tableName, String columnName, String comment) {
    return COLUMN_COMMENT
        + quote(tableName)
        + "."
        + quote(columnName)
        + IS
        + escapeLiteral(comment)
        + "'";
  }

  private static String addColumnSql(String tableName, String columnClause) {
    return ALTER_TABLE + quote(tableName) + " ADD (" + columnClause + ")";
  }

  private static String modifyColumnSql(String tableName, String columnClause) {
    return ALTER_TABLE + quote(tableName) + " MODIFY (" + columnClause + ")";
  }
}
