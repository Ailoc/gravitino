  @Test
  public void testAlterTableRejectsUnsupportedChanges() {
    Assertions.assertThrows(
        IllegalArgumentException.class,
        () -> ops.generateAlterTableSql(SCHEMA, TABLE, TableChange.setProperty("k", "v")));

    Assertions.assertThrows(
        IllegalArgumentException.class,
        () -> ops.generateAlterTableSql(SCHEMA, TABLE, TableChange.removeProperty("k")));

    Assertions.assertThrows(
        IllegalArgumentException.class,
        () ->
            ops.generateAlterTableSql(
                SCHEMA,
                TABLE,
                TableChange.updateColumnPosition(
                    new String[] {"col1"}, TableChange.ColumnPosition.after("col2"))));

    // IDENTITY cannot be added to or dropped from an existing column.
    Assertions.assertThrows(
        UnsupportedOperationException.class,
        () ->
            ops.generateAlterTableSql(
                SCHEMA, TABLE, TableChange.updateColumnAutoIncrement(new String[] {"col1"}, true)));
  }

