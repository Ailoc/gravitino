  @Test
  public void testDatetimePrecision() {
    Assertions.assertEquals(3, ops.calculateDatetimePrecision("datetime", 23, 0));
    Assertions.assertEquals(0, ops.calculateDatetimePrecision("smalldatetime", 16, 0));
    Assertions.assertEquals(7, ops.calculateDatetimePrecision("datetime2", 27, 7));
    Assertions.assertEquals(7, ops.calculateDatetimePrecision("datetimeoffset", 34, 7));
    Assertions.assertEquals(4, ops.calculateDatetimePrecision("time", 13, 4));
    // Non temporal types report no precision.
    Assertions.assertNull(ops.calculateDatetimePrecision("int", 10, 0));
  }

